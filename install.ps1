# QuantDesk installer - Windows PowerShell. Idempotent: safe to re-run.
# After installing,  quantdesk  works in any new terminal.
$ErrorActionPreference = "Stop"
Set-Location $PSScriptRoot
$QD_HOME = (Get-Location).Path

Write-Host "== QuantDesk installer =="

# ---------------------------------------------------------- 1. python env
$needInstall = $true
if (Test-Path ".venv\Scripts\python.exe") {
    & .venv\Scripts\python.exe -c "import fastapi, numpy, pandas, statsmodels, yfinance" 2>$null
    if ($LASTEXITCODE -eq 0) { $needInstall = $false }
}

if ($needInstall) {
    if (Test-Path .venv) { Remove-Item -Recurse -Force .venv }

    $py = $null
    foreach ($cand in @("py", "python", "python3")) {
        if (Get-Command $cand -ErrorAction SilentlyContinue) { $py = $cand; break }
    }
    if (-not $py) {
        Write-Host "!! Python not found."
        Write-Host "   Install it from https://www.python.org/downloads/"
        Write-Host '   IMPORTANT: tick "Add python.exe to PATH" in the installer.'
        Write-Host "   Then re-run this script."
        exit 1
    }
    if ($py -eq "py") { $py = "py -3" }

    Write-Host "[*] creating venv with $py"
    Invoke-Expression "$py -m venv .venv"
    Write-Host "[*] installing dependencies (1-3 minutes)"
    & .venv\Scripts\python.exe -m pip install --upgrade pip --quiet
    & .venv\Scripts\python.exe -m pip install -r requirements.txt
}
else {
    Write-Host "[*] environment already installed - skipping"
}

# ---------------------------------------------------------- 2. launcher
$binDir = Join-Path $env:LOCALAPPDATA "Programs\quantdesk\bin"
New-Item -ItemType Directory -Force -Path $binDir | Out-Null

$shimContent = @"
@echo off
REM QuantDesk launcher shim (generated by install.ps1)
"$QD_HOME\qd.bat" %*
"@
Set-Content -Path (Join-Path $binDir "quantdesk.cmd") -Value $shimContent -Encoding ASCII

# add to user PATH if not already there
$userPath = [Environment]::GetEnvironmentVariable("Path", "User")
if ($userPath -notlike "*$binDir*") {
    [Environment]::SetEnvironmentVariable("Path", "$userPath;$binDir", "User")
    Write-Host "[*] added $binDir to your user PATH"
}

Write-Host ""
Write-Host "[ok] installed."
Write-Host "     Open a NEW terminal, then from ANYWHERE run:"
Write-Host ""
Write-Host "         quantdesk            # start server + open browser"
Write-Host "         quantdesk status     # is it running?"
Write-Host "         quantdesk stop       # shut it down"
Write-Host "         quantdesk doctor     # diagnose problems"
