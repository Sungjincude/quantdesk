#!/usr/bin/env bash
# QuantDesk installer — Linux & macOS. Idempotent: safe to re-run.
# After installing, the command  quantdesk  works in any terminal.
set -euo pipefail
cd "$(dirname "$0")"
QD_HOME="$(pwd)"

echo "== QuantDesk installer =="

# ---------------------------------------------------------- 1. python env
if [ -x .venv/bin/python ] \
   && .venv/bin/python -c 'import fastapi, numpy, pandas, statsmodels, yfinance' \
        >/dev/null 2>&1; then
    echo "[*] environment already installed - skipping"
else
    rm -rf .venv
    if command -v uv >/dev/null 2>&1; then
        echo "[*] creating venv with uv"
        uv venv .venv --python 3.11
        uv pip install --python .venv/bin/python -r requirements.txt
    elif command -v python3 >/dev/null 2>&1 \
         && python3 -c 'import sys; assert sys.version_info >= (3,10)' 2>/dev/null \
         && python3 -m venv .venv 2>/dev/null; then
        echo "[*] created venv with $(python3 -V)"
        .venv/bin/pip install --upgrade pip >/dev/null
        .venv/bin/pip install -r requirements.txt
    else
        echo "!! Could not create a Python environment."
        echo "   Easiest fix - install uv (https://docs.astral.sh/uv/):"
        echo "      curl -LsSf https://astral.sh/uv/install.sh | sh"
        echo "   Or on Debian/Mint/Ubuntu:"
        echo "      sudo apt install python3 python3-venv python3-pip"
        exit 1
    fi
fi

# ---------------------------------------------------------- 2. launcher
BIN_DIR="$HOME/.local/bin"
mkdir -p "$BIN_DIR"
cat > "$BIN_DIR/quantdesk" <<EOF
#!/usr/bin/env bash
# QuantDesk launcher shim (generated by install.sh)
exec "$QD_HOME/qd" "\$@"
EOF
chmod +x "$BIN_DIR/quantdesk" "$QD_HOME/qd"

# ---------------------------------------------------------- 3. PATH check
case ":$PATH:" in
    *":$BIN_DIR:"*) : ;;
    *)
        echo "[*] adding $BIN_DIR to PATH (.bashrc / .zshrc)"
        for RC in "$HOME/.bashrc" "$HOME/.zshrc"; do
            [ -f "$RC" ] && grep -qs "$BIN_DIR" "$RC" || \
                echo "export PATH=\"$BIN_DIR:\$PATH\"" >> "$RC" 2>/dev/null || true
        done
        ;;
esac

echo ""
echo "[ok] installed."
echo "     Open a NEW terminal, then from ANYWHERE run:"
echo ""
echo "         quantdesk            # start server + open browser"
echo "         quantdesk status     # is it running?"
echo "         quantdesk stop       # shut it down"
echo "         quantdesk doctor     # diagnose problems"
